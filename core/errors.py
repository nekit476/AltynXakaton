"""Общая иерархия прикладных ошибок.

Сервисы и селекторы (domain/) бросают наследников AppError, views (web/) ловят их одним
`except AppError` и превращают в понятный ответ. Контекст ошибки лежит в атрибутах,
а не только в тексте, — чтобы тесты и обработчики проверяли причину, а не строку.
"""


class AppError(Exception):
    """Общий предок всех прикладных ошибок проекта."""


class NotFound(AppError):
    """Объекта нет или он чужой.

    Для пользователя эти случаи неразличимы намеренно: на чужую заявку отдаём 404,
    а не 403, чтобы по коду ответа нельзя было узнать, что объект существует.
    """

    def __init__(self, entity: str, entity_id: object) -> None:
        self.entity = entity
        self.entity_id = entity_id
        super().__init__(f"{entity} {entity_id} не найден")
