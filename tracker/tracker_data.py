@dataclass(frozen=True)
class Blocker:
    """Межличностная зависимость: задача `waiting` ждёт `blocking` другого участника."""

    waiting: Task
    blocking: Task
    slack_days: int  # сколько полных дней между готовностью блокера и стартом
    risk: str
    plan_b: str


def risk_for_slack(slack_days: int) -> str:
    """Готов в тот же день или позже — высокий риск, накануне — средний."""
    if slack_days < 0:
        return "Высокий"
    if slack_days == 0:
        return "Средний"
    return "Низкий"


def blockers() -> list[Blocker]:
    """Все зависимости между разными владельцами, по порядку ID ждущей задачи.

    Свои зависимости участник разруливает сам порядком работы, поэтому
    блокером считается только чужая задача.
    """
    result = []
    for task in TASKS:
        for dep_id in task.deps:
            dep = TASK_BY_ID[dep_id]
            if dep.owner == task.owner:
                continue
            # Задача готова в конце дня dep.end, начать с неё можно со следующего:
            # запас = start - (end + 1).
            slack = task.start - dep.end - 1
            plan_b = task.plan_b or DEFAULT_PLAN_B.get(
                (task.owner, dep.owner), "Обсудить на синке"
            ).format(dep=dep.id)
            result.append(Blocker(task, dep, slack, risk_for_slack(slack), plan_b))
    return result


def stage_of_day(d: int) -> Stage:
    return next(s for s in STAGES if s.start <= d <= s.end)


def day_plan(tasks: list[Task], d: int) -> list[tuple[Task, str]]:
    """Что делать с задачами в день d: начать, продолжить, закончить или сделать за день.

    Одна функция для листа «По_дням», HTML- и md-планов, чтобы формулировки
    не разошлись.
    """
    result = []
    for t in tasks:
        if not t.start <= d <= t.end:
            continue
        if t.start == d == t.end:
            action = "сделать"
        elif t.start == d:
            action = "начать"
        elif t.end == d:
            action = "закончить"
        else:
            action = "продолжить"
        result.append((t, action))
    return result


def tasks_of(code: str) -> list[Task]:
    """Задачи, где участник владелец или соучастник."""
    return [t for t in TASKS if t.owner == code or code in t.co]


def dependents_of(task_id: int) -> list[Task]:
    """Задачи, которые ждут данную."""
    return [t for t in TASKS if task_id in t.deps]
